test('the poll interval never drops below 60 s and backs off to 15 minutes', () => {
  assert.equal(nextDelay(0), POLL_MS);
  for (const r of [0, 0.5, 0.999]) {
    let prev = 0;
    for (let f = 1; f < 30; f++) {
      const d = nextDelay(f, () => r);
      assert.ok(d >= POLL_MS && d <= MAX_BACKOFF_MS, `failure ${f}: ${d}`);
      assert.ok(d >= prev, 'backoff shrank while the camera stayed down');
      prev = d;
    }
    assert.equal(nextDelay(29, () => r), MAX_BACKOFF_MS);
  }
});

function fakeFetch(responses) {
  const calls = [];
  const fetch = async (url, init) => {
    calls.push({ url, headers: init.headers });
    const next = responses.shift();
    if (next instanceof Error) throw next;
    const { status = 200, headers = {}, body = Buffer.alloc(0) } = next;
    return {
      status,
      headers: { get: (k) => headers[k.toLowerCase()] ?? null },
      arrayBuffer: async () => body,
    };
  };
  return { fetch, calls };
}

test('polls are conditional, identify the station, and report each outcome', async () => {
  const body = Buffer.from([0xff, 0xd8, 1, 2, 3]);
  const { fetch, calls } = fakeFetch([
    { headers: { 'content-type': 'image/jpeg', etag: '"abc"', 'last-modified': 'Sun, 11 Oct 2026 03:00:00 GMT' }, body },
    { status: 304 },
    { status: 503 },
    { headers: { 'content-type': 'text/html' }, body: Buffer.from('<html>') },
    Object.assign(new Error('fetch failed'), { cause: { code: 'ECONNREFUSED' } }),
  ]);
  const poller = createPoller({ fetch });

  const first = await poller.poll();
  assert.equal(first.kind, 'frame');
  assert.equal(first.lastModified, 'Sun, 11 Oct 2026 03:00:00 GMT');
  assert.match(first.hash, /^[0-9a-f]{64}$/);
  assert.equal(calls[0].url, SOURCE_URL);
  assert.equal(calls[0].headers['User-Agent'], USER_AGENT);
  assert.doesNotMatch(USER_AGENT, /Mozilla|Chrome|Safari/, 'not a browser string');
  assert.match(USER_AGENT, /github\.com\/schmug\/endless-memory/);
  assert.equal(calls[0].headers['If-None-Match'], undefined, 'nothing to be conditional on yet');

  assert.deepEqual(await poller.poll(), { kind: 'unchanged', status: 304 });
  assert.equal(calls[1].headers['If-None-Match'], '"abc"');
  assert.equal(calls[1].headers['If-Modified-Since'], 'Sun, 11 Oct 2026 03:00:00 GMT');

  assert.equal((await poller.poll()).kind, 'error');
  const html = await poller.poll();
  assert.equal(html.kind, 'error');
  assert.match(html.reason, /content-type/);
  assert.deepEqual(await poller.poll(), { kind: 'error', reason: 'ECONNREFUSED' });
});

// ---------------------------------------------------------------------------
// The ladder as the renderer drives it. The decode is faked: a frame's "bytes" are a
// one-byte luma value, so the hour of station time below costs no ffmpeg.
// ---------------------------------------------------------------------------

const fakeDecode = (bytes) => {
  if (bytes[0] === 0) throw new RefusedFrame('wrong size');
  const luma = Uint8Array.from({ length: COLS * ROWS }, (_, i) => (i * 7 + bytes[0] * 31) % 256);
  return { luma, rgb: Uint8Array.from({ length: COLS * ROWS * 3 }, (_, i) => (i % 3 === 2 ? 180 : luma[(i / 3) | 0] >> 1)) };
};
const ARCHIVE_GRID = (() => {
  const luma = Uint8Array.from({ length: COLS * ROWS }, (_, i) => (i % COLS) + 40);
  return { luma, rgb: Uint8Array.from({ length: COLS * ROWS * 3 }, (_, i) => luma[(i / 3) | 0]) };
})();
const frameOf = (v, lastModified = null) => ({ kind: 'frame', bytes: Buffer.from([v]), hash: `h${v}`, lastModified, status: 200 });

function station() {
  const clock = testClock();
  const log = [];
  const vf = createVideoFrame({ now: clock.now, decode: fakeDecode, archiveGrid: ARCHIVE_GRID, log: (o) => log.push(o) });
  return { clock, vf, log };
}

// Criterion 5, at the level this module owns: the run loop decodes the committed still
// before anything else, and with nothing cached that is what renders.
test('a cold start renders the archive still, captioned as archive', () => {
  const { vf } = station();
  const f = vf.frame();
  assert.equal(f.state, ARCHIVE);
  assert.deepEqual(f.lines, toGlyphs(autoLevel(ARCHIVE_GRID.luma).levelled));
  assert.equal(f.caption, `Boston Light, west - archive ${ARCHIVE_DATE} — not live`);
  vf.record({ kind: 'error', reason: 'ECONNREFUSED' });
  assert.equal(vf.frame().state, ARCHIVE);
});

test('a cold start needs the archive still and says so', () => {
  assert.throws(() => createVideoFrame({ now: () => 0, archiveGrid: null }), /archive still/);
});

test('a new frame goes live with its own capture time in the caption', () => {
  const { vf, log } = station();
  vf.record(frameOf(1, 'Sun, 11 Oct 2026 02:59:30 GMT'));
  const f = vf.frame();
  assert.equal(f.state, LIVE);
  assert.equal(f.caption, 'Boston Light, west - 2026-10-11 02:59 UTC - live');
  assert.deepEqual(f.lines, toGlyphs(autoLevel(fakeDecode([1]).luma).levelled), 'first frame after archive is not blended with it');
  const polled = log.find((e) => e.event === 'poll');
  assert.equal(typeof polled.span, 'number');
});

// Criterion 6's regression, through the renderer: a camera that keeps serving the
// same bytes stops being captioned live six minutes after the last DIFFERENT frame.
test('a frozen camera stops claiming live six minutes after its last new frame', () => {
  const { clock, vf } = station();
  vf.record(frameOf(1));
  const states = [];
  for (let m = 1; m <= 40; m++) {
    clock.advance(MIN);
    vf.record(frameOf(1));
    states.push([m, vf.frame()]);
  }
  for (const [m, f] of states) {
    if (m < 6) assert.equal(f.state, LIVE, `minute ${m}`);
    else assert.notEqual(f.caption.endsWith(' - live'), true, `minute ${m} still claims live`);
  }
  assert.equal(states[5][1].state, HELD);
  assert.match(states[5][1].caption, /held, frame 6 min old$/);
  assert.equal(states[39][1].state, ARCHIVE);
});

// Criterion 2's second half: declining to publish means holding the previous frame.
test('a refused frame holds the previous picture and ages like a failed fetch', () => {
  const { clock, vf, log } = station();
  vf.record(frameOf(1));
  const before = vf.frame().lines;
  clock.advance(MIN);
  vf.record(frameOf(0));   // fakeDecode refuses byte 0
  assert.deepEqual(vf.frame().lines, before);
  assert.ok(log.some((e) => e.result === 'refused'));
  clock.advance(6 * MIN);
  vf.record(frameOf(0));
  assert.equal(vf.frame().state, HELD);
  assert.deepEqual(vf.frame().lines, before);
});

test('a repeat is not decoded again', () => {
  let decodes = 0;
  const vf = createVideoFrame({ now: () => 0, decode: (b) => { decodes++; return fakeDecode(b); }, archiveGrid: ARCHIVE_GRID });
  vf.record(frameOf(1));
  vf.record(frameOf(1));
  vf.record({ kind: 'unchanged', status: 304 });
  assert.equal(decodes, 1);
});

test('recovery from ARCHIVE is immediate and unblended', () => {
  const { clock, vf } = station();
  vf.record(frameOf(1));
  clock.advance(45 * MIN);
  assert.equal(vf.frame().state, ARCHIVE);
  vf.record(frameOf(2));
  const f = vf.frame();
  assert.equal(f.state, LIVE);
  assert.deepEqual(f.lines, toGlyphs(autoLevel(fakeDecode([2]).luma).levelled));
});

test('consecutive live frames are smoothed, and churn is logged against the last render', () => {
  const { clock, vf, log } = station();
  vf.record(frameOf(1));
  vf.frame();
  clock.advance(MIN);
  vf.record(frameOf(2));
  const f = vf.frame();
  assert.notDeepEqual(f.lines, toGlyphs(autoLevel(fakeDecode([2]).luma).levelled), 'the second frame was not averaged');
  const polls = log.filter((e) => e.result === 'frame');
  assert.equal(polls.length, 2);
  assert.ok(polls[1].churn > 0 && polls[1].churn <= 1);
});

test('the archive still and a fresh live frame are inked in their own camera colour', () => {
  const { vf } = station();
  assert.deepEqual(vf.frame().ink, cameraInk(ARCHIVE_GRID.rgb));
  vf.record(frameOf(1));
  assert.deepEqual(vf.frame().ink, cameraInk(fakeDecode([1]).rgb), 'first frame after archive is not blended with it');
});

test('live colour is smoothed like the tone, and its shift is logged beside churn', () => {
  const { clock, vf, log } = station();
  vf.record(frameOf(1));
  vf.frame();
  clock.advance(MIN);
  vf.record(frameOf(2));
  assert.notDeepEqual(vf.frame().ink, cameraInk(fakeDecode([2]).rgb), 'the second frame\'s colour was not averaged');
  const polls = log.filter((e) => e.result === 'frame');
  assert.equal(polls[0].inkShift, null);
  assert.ok(polls[1].inkShift > 0 && polls[1].inkShift <= 1);
});

test('the PNG is published by rename, leaving no temporary file', () => {
  const out = join(dir, 'pub', 'frame.png');
  spawnSync('mkdir', ['-p', join(dir, 'pub')]);
  publish(out, Buffer.from('one'));
  publish(out, Buffer.from('two'));
  assert.equal(readFileSync(out, 'utf8'), 'two');
  assert.deepEqual(readdirSync(join(dir, 'pub')), ['frame.png']);
  assert.ok(existsSync(out));
});
